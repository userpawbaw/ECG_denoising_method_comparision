def _strip_code(text: str) -> str:
    return re.sub(r"`[^`]*`", " ", text)


def _latin_words(text: str, ctx: dict) -> list[str]:
    out = []
    for m in re.finditer(r"(?<![A-Za-z0-9_\-])([A-Za-z][A-Za-z\-]+)(?![A-Za-z0-9_])", _strip_code(text)):
        w = m.group(1)
        if ctx.get("latin_fix"):                          # F: 파일 확장자 · 「t-검정」 · 한국어 뒤 괄호 원어 병기는 빼기
            w = w.rstrip("-")
            before = text[:m.start()]
            if before.endswith(".") or len(w) < 2 or w in ("rad",) or re.search(r"[가-힣]\s?\([^()]*$", before):
                continue
        if w in COMMON_LATIN or w in NAMES or w in ABBREV or ctx.get("t1_upper_ok", True) and w.isupper():
            continue
        if len(w) < ctx.get("latin_min", 2):
            continue
        out.append(w)
    return out


def _loanwords(text: str, ctx: dict) -> list[str]:
    return [w for w in ctx.get("loanwords", LOANWORDS) if w in text]


def _abbrev_no_gloss(text: str, ctx: dict) -> list[str]:
    """C5 — 약어가 나오는데 그 문장(T1) 또는 그 문서의 앞선 부분(F)에 풀이가 없다."""
    out = []
    seen = ctx.setdefault("abbrev_seen", set())
    for a in sorted(ctx.get("abbrev_set", ABBREV)):
        for m in re.finditer(rf"(?<![A-Za-z0-9_\-]){re.escape(a)}(?![A-Za-z0-9_\-])", _strip_code(text)):
            glossed = re.search(rf"[가-힣]\s*\(\s*{re.escape(a)}|{re.escape(a)}\s*\(\s*[가-힣A-Za-z]", text)
            if ctx.get("abbrev_scope") == "document":
                if glossed:
                    seen.add(a)
                if a not in seen:
                    out.append(a); seen.add(a)
            elif not glossed:
                out.append(a)
            break
    return out


def _coined(text: str, ctx: dict) -> list[str]:
    out = []
    seen = ctx.setdefault("coined_seen", set())
    for t in COINED:
        if t in text:
            if ctx.get("coined_scope") == "document":
                defined = re.search(re.escape(t) + r"\s*\(|" + re.escape(t) + r"[은는]\s[^.]{0,40}(뜻|말|가리킨|정의|이다)", text)
                if t in seen:
                    continue
                seen.add(t)
                if defined:
                    continue
            out.append(t)
    return out


def _long(text: str, ctx: dict) -> list[str]:
    n = len(_strip_code(text))
    conn = len(re.findall(r"(는데|지만|므로|어서|아서|으며|이며|하고|되고|이고|면서|니까|더라도|[가-힣]고,|[가-힣]며,)", text))
    lim, clim = ctx.get("long_chars", 110), ctx.get("long_conn", 3)
    out = []
    if n > lim:
        out.append(f"{n}자")
    if conn >= clim:
        out.append(f"연결어미 {conn}개")
    return out


def _fragment(text: str, ctx: dict) -> list[str]:
    kind = ctx.get("kind", "")
    if kind in ("표", "제목") and not ctx.get("fragment_in_tables"):
        return []
    t = re.sub(r"[\s*`)\]」»\"'.]+$", "", text)
    if len(t) < ctx.get("fragment_min", {}).get(ctx.get("source", ""), 6):
        return []
    if re.search(r"(다|요|음|함|임|됨|까|가|나|라)$", t):
        return []
    if t.endswith((":", "—", "·")):
        return ["미완결 종결"]
    return ["서술어 없음"]


def _question_heading(text: str, ctx: dict) -> list[str]:
    out = []
    kind = ctx.get("kind", "")
    t = re.sub(r"[*`]", "", text).strip()
    if "?" in t:
        out.append("?")
    if kind in ("제목", "표"):
        m = re.search(r"([가-힣]+(?:는가|ㄴ가|나|까|가|이유|대가|경위|것))$", t)
        if m and kind == "제목":
            out.append(m.group(1))
        if kind == "제목" and re.search(r"[가-힣](다|었다|았다|했다|한다|된다|진다|났다|왔다|않는다|없다|있다)$", t):
            out.append("문장형 제목")
        if kind == "제목" and re.search(r"\s—\s", t):
            out.append("줄표 부제")
        if ctx.get("b8_wide"):
            m2 = re.search(r"(있나|했는가|되는가|하는가|했나|났나|넣었나|이유|것 하나|(?<=[가-힣])면)$", t)
            if m2 and kind == "제목":
                out.append(m2.group(1))
            if kind == "표" and re.fullmatch(r"(질문|답하는 실험|무엇|왜|무엇을 바꿨나|무엇으로 쟀나|무엇인가)", t):
                out.append(t)
    for k in ("무엇을 보나", "읽는 법", "자세히", "놓쳤다면", "재사용할 것"):
        if t.startswith(k):
            out.append(k)
    return out


def _quoted_speech(text: str, ctx: dict) -> list[str]:
    out = []
    for m in re.finditer(r"[「«\"]([^」»\"]{4,80})[」»\"]", text):
        q = m.group(1).strip()
        if re.search(r"(다|라|자|어|지|냐|까|마라|된다|않는다)[.!?]?$", q) or re.search(r"(우리|나는|내가)", q):
            out.append(q[:30])
    return out


def _vague_generic(text: str, ctx: dict) -> list[str]:
    """D1 — 「딥러닝」이 특정 모델을 가리키는데 문장 안에 어떤 모델인지 없다."""
    if not re.search(r"딥러닝|신경망|(?<![A-Za-z])DL(?![A-Za-z])", text):
        return []
    if re.search(r"M0\d|U-Net|ResUNet|잔차|웨이블릿 U|모델 [A-Z]|`m0", text):
        return []
    return [m.group(0) for m in re.finditer(r"딥러닝|신경망|(?<![A-Za-z])DL(?![A-Za-z])", text)][:2]


def _no_reference(text: str, ctx: dict) -> list[str]:
    """D2 — 비교 · 최상급 표현이 있는데 비교 기준이 문장 안에 없다."""
    pat = ctx.get("cmp_pat", r"(가장|최고|최저|최하위|최상위|우위|열세|우세|(?<![가-힣])더\s|(?<![가-힣])덜\s|낫다|나은\s|나빠|좋아졌|나빠졌)")
    hits = [m.group(0).strip() for m in re.finditer(pat, text)]
    if not hits:
        return []
    if re.search(r"(보다|대비|비해|에 비하면|중에서|중\s|가운데|vs|기준으로|기준\s|와 비교|과 비교|순위)", text):
        return []
    return hits[:2]


def _vague_eval(text: str, ctx: dict) -> list[str]:
    hits = [m.group(0) for m in re.finditer(r"성능|(?<![가-힣])잘\s|좋은 결과|효과적|우수|뛰어나|좋다|좋았|나쁘다|나빴", text)]
    if not hits:
        return []
    if ctx.get("eval_needs_metric", True) and re.search(r"(SNR|dB|지표|상관|오차|개선량|%|ms|RMSE|PRD|순위|가성)", text):
        return []
    return hits[:2]


