# =====================================================================  규칙 형식
@dataclass(frozen=True)
class Rule:
    rid: str                      # 범주 번호 (A1 …)
    name: str
    define: str                   # 범주 정의 — 무엇을 수정 대상으로 보나
    include: str                  # 판정 기준 — 포함하는 경우
    exclude: str                  # 판정 기준 — 제외하는 경우
    guide: str                    # 교정 지침
    examples: tuple[tuple[str, str], ...] = ()   # (수정 전, 수정 후)
    patterns: tuple[str, ...] = ()
    func: Callable[[str, dict], list[str]] | None = None
    mode: str = "자동"            # 자동 · 자동+수동 · 수동 (수동 = 개방 코딩 · 사람 판정으로만)
    tier: int = 1                 # 1 = 뜻 · 독자 이해에 영향 / 2 = 표기 · 문체 다듬기
    note: str = ""                # 판 사이 변경 기록
    raw: bool = False             # True = 코드 서식(`…`) 안까지 본다

    @property
    def group(self) -> str:
        return self.rid[0]

    def hits(self, text: str, ctx: dict) -> list[str]:
        out: list[str] = []
        body = text if self.raw else ctx.get("plain", text)
        for p in self.patterns:
            out += [m.group(0).strip() for m in re.finditer(p, body)]
        if self.func:
            out += self.func(text, ctx)
        return [h for h in out if h]


