def open_category(code: str, detail: str, version: str) -> str | None:
    """개방 코드 하나를 규칙판의 범주로. F 는 대조에서 드러난 코드표 경계를 바로잡는다."""
    if code == "CO" and detail.startswith("재사용할 것"):
        return "E2"
    if version != "T1":
        if code == "AR" and "—" in detail:
            return "B2"                                   # 줄표를 기호(AR)로 적은 것 — 범주는 B2
        if code == "IC" and re.search(r"(?:^|·)\s*(?:[FDOP]-\d|STEP|O-\d|§)", detail):
            return "C2"                                   # 기록 번호를 내부 코드(IC)로 적은 것
        if code == "IC" and re.fullmatch(r"D\d", detail.strip()):
            return "C4"
        if code in ("CO", "IT", "구어", "내부 용어") and re.fullmatch(r"(?:판|칸|판 수|한 판|쌍|팔당 11 판|팔당 판)", detail.strip()):
            return "A3"                                   # 판 · 칸은 비유로 만든 내부 용어 — A3 에서 다룬다
        if code in ("CO", "구어") and detail.strip() in ("프로브", "튜닝"):
            return "A6"
        if code in ("CO", "구어") and detail.strip() == "결정적":
            return "D4"
        if code == "SP":
            return "X"                                    # 개방 코딩은 「붙여 쓴 쪽」을 불일치로 표시 — 맞춤법상 옳은 쪽이다
    return OPEN_CODEBOOK.get(code)


